//! A JSON form of [`TypeSchema`] that round-trips exactly.
//!
//! Game modules compiled to WebAssembly describe their types with the same
//! macros the engine uses; this is how the description crosses the module
//! boundary (design note M5 §3). The host reads it back with [`from_wire`],
//! validates it, and either registers the type or checks it against the
//! engine's own declaration of the same name.
//!
//! ```json
//! { "name": "Coin", "doc": "...", "size": 4, "align": 4,
//!   "kind": { "struct": [ { "name": "value", "doc": "...", "offset": 0,
//!     "ty": { "name": "u32", "doc": "", "size": 4, "align": 4, "kind": "u32" },
//!     "range": [1, 100], "default": 1 } ] } }
//! ```

use serde_json::{Map, Value, json};
use wish_core::{Diagnostic, Result};

use crate::model::{FieldSchema, MAX_DEPTH, NumberRange, TypeKind, TypeSchema, VariantSchema};

/// The names of the kinds that carry no data of their own.
const SIMPLE: &[(&str, TypeKind)] = &[
    ("bool", TypeKind::Bool),
    ("i8", TypeKind::I8),
    ("i16", TypeKind::I16),
    ("i32", TypeKind::I32),
    ("i64", TypeKind::I64),
    ("u8", TypeKind::U8),
    ("u16", TypeKind::U16),
    ("u32", TypeKind::U32),
    ("u64", TypeKind::U64),
    ("f32", TypeKind::F32),
    ("f64", TypeKind::F64),
    ("vec2", TypeKind::Vec2),
    ("vec3", TypeKind::Vec3),
    ("vec4", TypeKind::Vec4),
    ("quat", TypeKind::Quat),
    ("mat4", TypeKind::Mat4),
    ("color", TypeKind::Color),
    ("entity", TypeKind::Entity),
    ("text", TypeKind::Text),
    ("asset_ref", TypeKind::AssetRef),
];

/// The wire form of a schema.
pub fn to_wire(schema: &TypeSchema) -> Value {
    let kind = match &schema.kind {
        TypeKind::Enum(variants) => json!({ "enum": variants.iter().map(|v| json!({
            "name": v.name, "doc": v.doc, "value": v.value,
        })).collect::<Vec<_>>() }),
        TypeKind::Array { element, len } => {
            json!({ "array": { "element": to_wire(element), "len": len } })
        }
        TypeKind::Struct(fields) => {
            json!({ "struct": fields.iter().map(field_to_wire).collect::<Vec<_>>() })
        }
        simple => SIMPLE
            .iter()
            .find(|(_, kind)| kind == simple)
            .map_or(Value::Null, |(name, _)| Value::from(*name)),
    };
    json!({
        "name": schema.name,
        "doc": schema.doc,
        "size": schema.size,
        "align": schema.align,
        "kind": kind,
    })
}

fn field_to_wire(field: &FieldSchema) -> Value {
    let mut out = Map::new();
    out.insert("name".to_owned(), Value::from(field.name.as_str()));
    out.insert("doc".to_owned(), Value::from(field.doc.as_str()));
    out.insert("offset".to_owned(), Value::from(field.offset));
    out.insert("ty".to_owned(), to_wire(&field.ty));
    if let Some(unit) = &field.unit {
        out.insert("unit".to_owned(), Value::from(unit.as_str()));
    }
    if let Some(range) = field.range {
        out.insert("range".to_owned(), json!([range.min, range.max]));
    }
    if let Some(default) = &field.default {
        out.insert("default".to_owned(), default.clone());
    }
    if !field.aliases.is_empty() {
        out.insert("aliases".to_owned(), json!(field.aliases));
    }
    Value::Object(out)
}

fn bad(path: &str, what: &str) -> Diagnostic {
    Diagnostic::error(
        "invalid_type_description",
        format!("A type description from a game module is malformed at {path}: {what}."),
        "Build game code with the engine's SDK; type descriptions are generated by its #[component] macros and should not be written by hand.",
    )
}

fn text(value: &Value, key: &str, path: &str) -> Result<String> {
    value
        .get(key)
        .and_then(Value::as_str)
        .map(str::to_owned)
        .ok_or_else(|| bad(path, &format!("'{key}' must be a string")))
}

fn number(value: &Value, key: &str, path: &str) -> Result<u32> {
    value
        .get(key)
        .and_then(Value::as_u64)
        .and_then(|n| u32::try_from(n).ok())
        .ok_or_else(|| bad(path, &format!("'{key}' must be a whole number")))
}

/// Reads a schema from its wire form. The result is checked with
/// [`TypeSchema::validate`], so a hostile description cannot produce a
/// layout the engine would misread.
pub fn from_wire(value: &Value) -> Result<TypeSchema> {
    let schema = read(value, "type", 0)?;
    schema.validate()?;
    Ok(schema)
}

fn read(value: &Value, path: &str, depth: usize) -> Result<TypeSchema> {
    if depth > MAX_DEPTH {
        return Err(bad(path, "it is nested too deeply"));
    }
    let name = text(value, "name", path)?;
    let doc = text(value, "doc", path)?;
    let size = number(value, "size", path)?;
    let align = number(value, "align", path)?;
    let path = format!("{path} '{name}'");
    let kind = match value.get("kind") {
        Some(Value::String(kind)) => SIMPLE
            .iter()
            .find(|(n, _)| n == kind)
            .map(|(_, k)| k.clone())
            .ok_or_else(|| bad(&path, &format!("'{kind}' is not a kind")))?,
        Some(Value::Object(kind)) if kind.len() == 1 => {
            if let Some(Value::Array(variants)) = kind.get("enum") {
                let mut out = Vec::new();
                for variant in variants {
                    let value = variant
                        .get("value")
                        .and_then(Value::as_u64)
                        .and_then(|v| u8::try_from(v).ok())
                        .ok_or_else(|| bad(&path, "an enum value must fit in a byte"))?;
                    out.push(VariantSchema {
                        name: text(variant, "name", &path)?,
                        doc: text(variant, "doc", &path)?,
                        value,
                    });
                }
                TypeKind::Enum(out)
            } else if let Some(array) = kind.get("array") {
                let element = array
                    .get("element")
                    .ok_or_else(|| bad(&path, "an array needs its element type"))?;
                TypeKind::Array {
                    element: Box::new(read(element, &path, depth + 1)?),
                    len: number(array, "len", &path)?,
                }
            } else if let Some(Value::Array(fields)) = kind.get("struct") {
                let mut out = Vec::new();
                for field in fields {
                    out.push(read_field(field, &path, depth)?);
                }
                TypeKind::Struct(out)
            } else {
                return Err(bad(&path, "the kind must be enum, array or struct"));
            }
        }
        _ => return Err(bad(&path, "'kind' is missing")),
    };
    Ok(TypeSchema {
        name,
        doc,
        size,
        align,
        kind,
    })
}

fn read_field(field: &Value, path: &str, depth: usize) -> Result<FieldSchema> {
    let name = text(field, "name", path)?;
    let path = format!("{path}.{name}");
    let ty = field
        .get("ty")
        .ok_or_else(|| bad(&path, "a field needs its type"))?;
    let range = match field.get("range") {
        None => None,
        Some(range) => {
            let ends: Option<Vec<f64>> = range
                .as_array()
                .map(|ends| ends.iter().filter_map(Value::as_f64).collect());
            match ends.as_deref() {
                Some([min, max]) => Some(NumberRange {
                    min: *min,
                    max: *max,
                }),
                _ => return Err(bad(&path, "a range is [min, max]")),
            }
        }
    };
    let aliases = match field.get("aliases") {
        None => Vec::new(),
        Some(Value::Array(names)) => names
            .iter()
            .map(|n| {
                n.as_str()
                    .map(str::to_owned)
                    .ok_or_else(|| bad(&path, "aliases are strings"))
            })
            .collect::<Result<_>>()?,
        Some(_) => return Err(bad(&path, "aliases are a list of strings")),
    };
    Ok(FieldSchema {
        name,
        doc: text(field, "doc", &path)?,
        offset: number(field, "offset", &path)?,
        ty: read(ty, &path, depth + 1)?,
        unit: match field.get("unit") {
            None => None,
            Some(unit) => Some(
                unit.as_str()
                    .map(str::to_owned)
                    .ok_or_else(|| bad(&path, "a unit is a string"))?,
            ),
        },
        range,
        default: field.get("default").cloned(),
        aliases,
    })
}
