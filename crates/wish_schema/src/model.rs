//! The runtime description of a type's layout and meaning.

use std::collections::BTreeSet;

use serde_json::Value;
use wish_core::{Diagnostic, Result};

use crate::json::{NoTexts, check_default, to_json};
use crate::plain::Plain;

/// Describes one type: its name, documentation, layout and structure.
#[derive(Clone, Debug, PartialEq)]
pub struct TypeSchema {
    /// The type's name, e.g. `"Transform"`, `"f32"` or `"[Vec3; 2]"`.
    pub name: String,
    /// Documentation, taken from the type's doc comment. May be empty.
    pub doc: String,
    /// Size in bytes, including padding.
    pub size: u32,
    /// Alignment in bytes: 1, 2, 4 or 8.
    pub align: u32,
    /// What the type is made of.
    pub kind: TypeKind,
}

/// What a type is made of.
#[derive(Clone, Debug, PartialEq)]
pub enum TypeKind {
    /// `bool`: one byte, 0 or 1.
    Bool,
    /// `i8`.
    I8,
    /// `i16`.
    I16,
    /// `i32`.
    I32,
    /// `i64`.
    I64,
    /// `u8`.
    U8,
    /// `u16`.
    U16,
    /// `u32`.
    U32,
    /// `u64`.
    U64,
    /// `f32`.
    F32,
    /// `f64`.
    F64,
    /// Two `f32`s: x, y.
    Vec2,
    /// Three `f32`s: x, y, z.
    Vec3,
    /// Four `f32`s: x, y, z, w.
    Vec4,
    /// A rotation as four `f32`s: x, y, z, w.
    Quat,
    /// A 4x4 matrix as sixteen `f32`s in column-major order.
    Mat4,
    /// A linear color as four `f32`s: r, g, b, a.
    Color,
    /// A reference to an entity.
    Entity,
    /// A handle to a string in the world's text table.
    Text,
    /// A handle to a string in the world's text table that holds an asset
    /// file reference (`"assets/models/crate.glb#Mesh0"`): stored like
    /// [`TypeKind::Text`], but checked as a path and known to tools as a
    /// file reference.
    AssetRef,
    /// A fieldless enum stored as one byte.
    Enum(Vec<VariantSchema>),
    /// A fixed-size array.
    Array {
        /// The element type.
        element: Box<TypeSchema>,
        /// The number of elements.
        len: u32,
    },
    /// A struct with named fields.
    Struct(Vec<FieldSchema>),
}

/// One variant of an enum.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct VariantSchema {
    /// The variant's name, as written in JSON.
    pub name: String,
    /// Documentation, taken from the variant's doc comment. May be empty.
    pub doc: String,
    /// The byte stored for this variant.
    pub value: u8,
}

/// The inclusive range a numeric field accepts.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct NumberRange {
    /// Smallest allowed value.
    pub min: f64,
    /// Largest allowed value.
    pub max: f64,
}

/// One field of a struct.
#[derive(Clone, Debug, PartialEq)]
pub struct FieldSchema {
    /// The field's name, as written in JSON.
    pub name: String,
    /// Documentation, taken from the field's doc comment. May be empty.
    pub doc: String,
    /// Offset in bytes from the start of the struct.
    pub offset: u32,
    /// The field's type.
    pub ty: TypeSchema,
    /// The unit the value is measured in, e.g. `"m/s"`.
    pub unit: Option<String>,
    /// The range the value must stay within. Numeric fields only.
    pub range: Option<NumberRange>,
    /// The value a new instance starts with, in JSON form.
    pub default: Option<Value>,
    /// Names people are likely to try instead of the real one. They are not
    /// accepted as input; they only make the "did you mean" hint exact.
    pub aliases: Vec<String>,
}

/// Sizes and offsets are stored as `u32`. A value that does not fit becomes
/// `u32::MAX`, which [`TypeSchema::validate`] then rejects.
fn to_u32(value: usize) -> u32 {
    u32::try_from(value).unwrap_or(u32::MAX)
}

/// The deepest a schema may nest structs and arrays.
pub const MAX_DEPTH: usize = 32;

/// The largest value a schema may describe, in bytes (1 MiB).
pub const MAX_VALUE_SIZE: u32 = 1 << 20;

/// The most nodes (fields and array elements, counted per element) a walk
/// over one value may visit. Every function that walks a value is bounded
/// by this.
pub const MAX_NODES: u64 = 1 << 20;

const INVALID_SCHEMA_HINT: &str = "Schemas are normally generated by #[component], #[resource], #[event] or #[schema]. \
     If this one was built by hand or came from a script module, fix the part the message names.";

fn invalid(path: &str, message: String) -> Diagnostic {
    Diagnostic::error("invalid_schema", message, INVALID_SCHEMA_HINT).at_path(path)
}

impl TypeKind {
    /// Size and alignment of kinds whose layout never varies. `None` for
    /// arrays and structs.
    pub fn fixed_layout(&self) -> Option<(u32, u32)> {
        Some(match self {
            Self::Bool | Self::I8 | Self::U8 | Self::Enum(_) => (1, 1),
            Self::I16 | Self::U16 => (2, 2),
            Self::I32 | Self::U32 | Self::F32 | Self::Text | Self::AssetRef => (4, 4),
            Self::I64 | Self::U64 | Self::F64 => (8, 8),
            Self::Vec2 | Self::Entity => (8, 4),
            Self::Vec3 => (12, 4),
            Self::Vec4 | Self::Quat | Self::Color => (16, 4),
            Self::Mat4 => (64, 4),
            Self::Array { .. } | Self::Struct(_) => return None,
        })
    }

    /// Whether this is an integer or floating-point number.
    pub fn is_number(&self) -> bool {
        matches!(
            self,
            Self::I8
                | Self::I16
                | Self::I32
                | Self::I64
                | Self::U8
                | Self::U16
                | Self::U32
                | Self::U64
                | Self::F32
                | Self::F64
        )
    }

    /// How a value of this kind is written in JSON, as a phrase for messages.
    pub fn json_form(&self) -> String {
        match self {
            Self::Bool => "true or false".to_owned(),
            Self::I8
            | Self::I16
            | Self::I32
            | Self::I64
            | Self::U8
            | Self::U16
            | Self::U32
            | Self::U64 => "an integer".to_owned(),
            Self::F32 | Self::F64 => "a number".to_owned(),
            Self::Vec2 => "an array [x, y]".to_owned(),
            Self::Vec3 => "an array [x, y, z]".to_owned(),
            Self::Vec4 | Self::Quat => "an array [x, y, z, w]".to_owned(),
            Self::Mat4 => "an array of 16 numbers in column-major order".to_owned(),
            Self::Color => "an array [r, g, b, a]".to_owned(),
            Self::Entity => "an entity id string such as \"12v3\", or \"null\"".to_owned(),
            Self::Text => "a string".to_owned(),
            Self::AssetRef => {
                "a project-relative file path string such as \"assets/models/crate.glb#Mesh0\", or \"\" for none".to_owned()
            }
            Self::Enum(_) => "a variant name as a string".to_owned(),
            Self::Array { len, .. } => format!("an array of {len} items"),
            Self::Struct(_) => "an object".to_owned(),
        }
    }
}

impl TypeSchema {
    /// The schema of a built-in type whose layout is fixed by its kind.
    pub fn primitive(name: &str, kind: TypeKind) -> Self {
        let (size, align) = kind.fixed_layout().unwrap_or((0, 1));
        Self {
            name: name.to_owned(),
            doc: String::new(),
            size,
            align,
            kind,
        }
    }

    /// The schema of a struct with named fields.
    pub fn structure(
        name: &str,
        doc: &str,
        size: usize,
        align: usize,
        fields: Vec<FieldSchema>,
    ) -> Self {
        Self {
            name: name.to_owned(),
            doc: doc.to_owned(),
            size: to_u32(size),
            align: to_u32(align),
            kind: TypeKind::Struct(fields),
        }
    }

    /// The schema of a fieldless enum stored as one byte.
    pub fn enumeration(name: &str, doc: &str, variants: Vec<VariantSchema>) -> Self {
        Self {
            name: name.to_owned(),
            doc: doc.to_owned(),
            size: 1,
            align: 1,
            kind: TypeKind::Enum(variants),
        }
    }

    /// The schema of a fixed-size array.
    pub fn array(element: TypeSchema, len: usize, size: usize, align: usize) -> Self {
        Self {
            name: format!("[{}; {len}]", element.name),
            doc: String::new(),
            size: to_u32(size),
            align: to_u32(align),
            kind: TypeKind::Array {
                element: Box::new(element),
                len: to_u32(len),
            },
        }
    }

    /// The size in bytes, as a `usize` for slicing.
    pub fn byte_len(&self) -> usize {
        self.size as usize
    }

    fn any_kind(&self, predicate: &dyn Fn(&TypeKind) -> bool) -> bool {
        if predicate(&self.kind) {
            return true;
        }
        match &self.kind {
            TypeKind::Array { element, .. } => element.any_kind(predicate),
            TypeKind::Struct(fields) => fields.iter().any(|field| field.ty.any_kind(predicate)),
            _ => false,
        }
    }

    /// Whether every byte of a value belongs to a field: no padding anywhere.
    pub fn is_padding_free(&self) -> bool {
        match &self.kind {
            TypeKind::Struct(fields) => {
                let mut spans: Vec<(u32, u32)> = fields
                    .iter()
                    .map(|field| (field.offset, field.ty.size))
                    .collect();
                spans.sort_unstable();
                let mut end = 0u32;
                for (offset, size) in spans {
                    if offset != end {
                        return false;
                    }
                    end = offset.saturating_add(size);
                }
                end == self.size && fields.iter().all(|field| field.ty.is_padding_free())
            }
            TypeKind::Array { element, .. } => element.is_padding_free(),
            _ => true,
        }
    }

    /// Whether the type holds a [`TypeKind::Text`] or [`TypeKind::AssetRef`]
    /// (both are text-table handles) anywhere inside it.
    pub fn contains_text(&self) -> bool {
        self.any_kind(&|kind| matches!(kind, TypeKind::Text | TypeKind::AssetRef))
    }

    /// Whether some byte patterns are not valid values of this type (it
    /// holds a `bool` or an enum), so bytes from an untrusted source must be
    /// checked with [`validate_bytes`](crate::validate_bytes) before use.
    pub fn needs_validation(&self) -> bool {
        self.any_kind(&|kind| matches!(kind, TypeKind::Bool | TypeKind::Enum(_)))
    }

    /// Whether a value's raw bytes can be hashed directly: there is no
    /// padding to skip and no text handle to resolve.
    pub fn is_raw_hashable(&self) -> bool {
        self.is_padding_free() && !self.contains_text()
    }

    /// Checks that the schema is internally consistent.
    ///
    /// Schemas produced by the attribute macros always pass. This exists for
    /// schemas that arrive from outside the compiler's guarantees, such as
    /// those shipped inside script modules.
    pub fn validate(&self) -> Result<()> {
        let mut path = format!("/{}", self.name);
        // Limits first: everything else (including this function's own
        // recursion) walks the schema, and a hostile schema must not be able
        // to make that walk run for ever or exhaust the stack.
        self.limits(&path, 0)?;
        self.validate_at(&mut path)
    }

    /// Checks the size limits and returns the number of nodes a full walk of
    /// a value visits (array elements counted once per element).
    fn limits(&self, path: &str, depth: usize) -> Result<u64> {
        if depth > MAX_DEPTH {
            return Err(invalid(
                path,
                format!(
                    "'{}' is nested more than {MAX_DEPTH} levels deep.",
                    self.name
                ),
            ));
        }
        if self.size > MAX_VALUE_SIZE {
            return Err(invalid(
                path,
                format!(
                    "'{}' takes {} bytes; a stored value can take at most {MAX_VALUE_SIZE} bytes.",
                    self.name, self.size
                ),
            ));
        }
        let inner = match &self.kind {
            TypeKind::Array { element, len } => {
                if element.size == 0 && *len > 0 {
                    return Err(invalid(
                        path,
                        format!(
                            "'{}' is an array of zero-size elements; such arrays hold no data.",
                            self.name
                        ),
                    ));
                }
                element
                    .limits(path, depth + 1)?
                    .saturating_mul(u64::from(*len))
            }
            TypeKind::Struct(fields) => {
                let mut total = 0u64;
                for field in fields {
                    total = total.saturating_add(field.ty.limits(path, depth + 1)?);
                }
                total
            }
            _ => 0,
        };
        let nodes = inner.saturating_add(1);
        if nodes > MAX_NODES {
            return Err(invalid(
                path,
                format!(
                    "'{}' has more than {MAX_NODES} fields and array elements in total.",
                    self.name
                ),
            ));
        }
        Ok(nodes)
    }

    /// Whether two schemas describe the same stored layout: the same names,
    /// sizes, alignments, field offsets, element counts and enum values,
    /// recursively. Documentation, units, ranges, defaults and aliases are
    /// ignored. Unlike comparing fingerprints, this cannot be fooled by a
    /// hash collision, so it is what decides whether stored bytes may be
    /// viewed as a Rust type.
    pub fn same_layout(&self, other: &TypeSchema) -> bool {
        if self.name != other.name || self.size != other.size || self.align != other.align {
            return false;
        }
        match (&self.kind, &other.kind) {
            (TypeKind::Enum(a), TypeKind::Enum(b)) => {
                a.len() == b.len()
                    && a.iter()
                        .zip(b)
                        .all(|(a, b)| a.name == b.name && a.value == b.value)
            }
            (
                TypeKind::Array {
                    element: a,
                    len: a_len,
                },
                TypeKind::Array {
                    element: b,
                    len: b_len,
                },
            ) => a_len == b_len && a.same_layout(b),
            (TypeKind::Struct(a), TypeKind::Struct(b)) => {
                a.len() == b.len()
                    && a.iter().zip(b).all(|(a, b)| {
                        a.name == b.name && a.offset == b.offset && a.ty.same_layout(&b.ty)
                    })
            }
            (a, b) => {
                core::mem::discriminant(a) == core::mem::discriminant(b)
                    && !matches!(
                        a,
                        TypeKind::Enum(_) | TypeKind::Array { .. } | TypeKind::Struct(_)
                    )
            }
        }
    }

    fn validate_at(&self, path: &mut String) -> Result<()> {
        if self.name.is_empty() {
            return Err(invalid(path, "A type has an empty name.".to_owned()));
        }
        if !matches!(self.align, 1 | 2 | 4 | 8) {
            return Err(invalid(
                path,
                format!(
                    "'{}' has alignment {}; only 1, 2, 4 and 8 are supported.",
                    self.name, self.align
                ),
            ));
        }
        if !self.size.is_multiple_of(self.align) {
            return Err(invalid(
                path,
                format!(
                    "'{}' has size {}, which is not a multiple of its alignment {}.",
                    self.name, self.size, self.align
                ),
            ));
        }
        if let Some((size, align)) = self.kind.fixed_layout()
            && (self.size, self.align) != (size, align)
        {
            return Err(invalid(
                path,
                format!(
                    "'{}' is declared with size {} and alignment {}, but its kind always has size {size} and alignment {align}.",
                    self.name, self.size, self.align
                ),
            ));
        }
        match &self.kind {
            TypeKind::Enum(variants) => self.validate_enum(variants, path),
            TypeKind::Array { element, len } => self.validate_array(element, *len, path),
            TypeKind::Struct(fields) => self.validate_struct(fields, path),
            _ => Ok(()),
        }
    }

    fn validate_enum(&self, variants: &[VariantSchema], path: &str) -> Result<()> {
        if variants.is_empty() {
            return Err(invalid(
                path,
                format!("Enum '{}' has no variants.", self.name),
            ));
        }
        let mut names = BTreeSet::new();
        let mut values = BTreeSet::new();
        for variant in variants {
            if variant.name.is_empty() || !names.insert(variant.name.as_str()) {
                return Err(invalid(
                    path,
                    format!(
                        "Enum '{}' has an empty or repeated variant name '{}'.",
                        self.name, variant.name
                    ),
                ));
            }
            if !values.insert(variant.value) {
                return Err(invalid(
                    path,
                    format!(
                        "Enum '{}' uses the value {} for more than one variant.",
                        self.name, variant.value
                    ),
                ));
            }
        }
        Ok(())
    }

    fn validate_array(&self, element: &TypeSchema, len: u32, path: &mut String) -> Result<()> {
        let restore = path.len();
        path.push_str("/element");
        let result = element.validate_at(path);
        path.truncate(restore);
        result?;
        if element.size.checked_mul(len) != Some(self.size) || element.align != self.align {
            return Err(invalid(
                path,
                format!(
                    "Array '{}' is declared with size {} and alignment {}, but {len} elements of '{}' need size {} and alignment {}.",
                    self.name,
                    self.size,
                    self.align,
                    element.name,
                    u64::from(element.size) * u64::from(len),
                    element.align
                ),
            ));
        }
        Ok(())
    }

    fn validate_struct(&self, fields: &[FieldSchema], path: &mut String) -> Result<()> {
        let mut names = BTreeSet::new();
        for field in fields {
            if field.name.is_empty() || !names.insert(field.name.as_str()) {
                return Err(invalid(
                    path,
                    format!(
                        "'{}' has an empty or repeated field name '{}'.",
                        self.name, field.name
                    ),
                ));
            }
        }
        let mut aliases = BTreeSet::new();
        for field in fields {
            for alias in &field.aliases {
                if names.contains(alias.as_str()) || !aliases.insert(alias.as_str()) {
                    return Err(invalid(
                        path,
                        format!(
                            "'{}' uses the alias '{alias}' more than once, or for a name that is already a field.",
                            self.name
                        ),
                    ));
                }
            }
        }
        for field in fields {
            let restore = path.len();
            path.push_str("/fields/");
            path.push_str(&field.name);
            let result = self.validate_field(field, path);
            path.truncate(restore);
            result?;
        }
        let mut spans: Vec<(u32, u32, &str)> = fields
            .iter()
            .filter(|field| field.ty.size > 0)
            .map(|field| (field.offset, field.ty.size, field.name.as_str()))
            .collect();
        spans.sort_unstable();
        for pair in spans.windows(2) {
            if let [
                (first_offset, first_size, first_name),
                (second_offset, _, second_name),
            ] = pair
                && first_offset.saturating_add(*first_size) > *second_offset
            {
                return Err(invalid(
                    path,
                    format!(
                        "Fields '{first_name}' and '{second_name}' of '{}' overlap.",
                        self.name
                    ),
                ));
            }
        }
        Ok(())
    }

    fn validate_field(&self, field: &FieldSchema, path: &mut String) -> Result<()> {
        field.ty.validate_at(path)?;
        if !field.offset.is_multiple_of(field.ty.align) {
            return Err(invalid(
                path,
                format!(
                    "Field '{}' of '{}' is at offset {}, which is not a multiple of its alignment {}.",
                    field.name, self.name, field.offset, field.ty.align
                ),
            ));
        }
        if field
            .offset
            .checked_add(field.ty.size)
            .is_none_or(|end| end > self.size)
        {
            return Err(invalid(
                path,
                format!(
                    "Field '{}' of '{}' ends past the type's size of {} bytes.",
                    field.name, self.name, self.size
                ),
            ));
        }
        if field.ty.align > self.align {
            return Err(invalid(
                path,
                format!(
                    "Field '{}' needs alignment {}, but '{}' is only aligned to {}.",
                    field.name, field.ty.align, self.name, self.align
                ),
            ));
        }
        if let Some(range) = field.range {
            if !field.ty.kind.is_number() {
                return Err(invalid(
                    path,
                    format!(
                        "Field '{}' of '{}' has a range, but ranges apply to integer and floating-point fields only.",
                        field.name, self.name
                    ),
                ));
            }
            if !range.min.is_finite() || !range.max.is_finite() || range.min > range.max {
                return Err(invalid(
                    path,
                    format!(
                        "Field '{}' of '{}' has the range {}..={}, which is empty or not finite.",
                        field.name, self.name, range.min, range.max
                    ),
                ));
            }
        }
        if let Err(problem) = check_default(&self.name, field) {
            return Err(invalid(
                path,
                format!(
                    "The default of field '{}' of '{}' is not a valid value: {}",
                    field.name, self.name, problem.message
                ),
            ));
        }
        Ok(())
    }
}

impl VariantSchema {
    /// Describes one enum variant.
    pub fn new(name: &str, doc: &str, value: u8) -> Self {
        Self {
            name: name.to_owned(),
            doc: doc.to_owned(),
            value,
        }
    }
}

impl FieldSchema {
    /// Describes a field at `offset` bytes from the start of its struct.
    pub fn new(name: &str, doc: &str, offset: usize, ty: TypeSchema) -> Self {
        Self {
            name: name.to_owned(),
            doc: doc.to_owned(),
            offset: to_u32(offset),
            ty,
            unit: None,
            range: None,
            default: None,
            aliases: Vec::new(),
        }
    }

    /// Sets the unit the value is measured in.
    #[must_use]
    pub fn with_unit(mut self, unit: &str) -> Self {
        self.unit = Some(unit.to_owned());
        self
    }

    /// Sets the inclusive range the value must stay within.
    #[must_use]
    pub fn with_range(mut self, min: f64, max: f64) -> Self {
        self.range = Some(NumberRange { min, max });
        self
    }

    /// Sets the default value, in JSON form.
    #[must_use]
    pub fn with_default(mut self, default: Value) -> Self {
        self.default = Some(default);
        self
    }

    /// Sets the default from a Rust value of the field's type.
    ///
    /// The value is converted to JSON through the field's schema, so the Rust
    /// default is the single source of truth. Text defaults other than the
    /// empty string cannot be expressed (a handle only has meaning inside a
    /// world) and leave the default unset.
    #[must_use]
    pub fn with_default_of<T: Plain>(mut self, value: &T) -> Self {
        let mut bytes = vec![0u8; size_of::<T>()];
        value.encode(&mut bytes);
        self.default = to_json(&self.ty, &bytes, &NoTexts).ok();
        self
    }

    /// Adds a name people are likely to try instead of the real one.
    #[must_use]
    pub fn with_alias(mut self, alias: &str) -> Self {
        self.aliases.push(alias.to_owned());
        self
    }
}
