//! A game module in a world: its manifest, its types, its systems.
//!
//! [`GameModule::load`] compiles a module and reads its manifest (types and
//! systems, design note M5 §3). [`GameModule::install`] registers the
//! module's types in a world (the engine's own types must match the
//! engine's declarations exactly). [`ScriptRuntime::systems`] gives the
//! systems to add to an app: each call builds the frame from the world,
//! runs the system in the tick's instance, writes back what changed and
//! applies the commands.

use std::collections::{BTreeMap, BTreeSet};
use std::sync::{Arc, Mutex};

use serde_json::Value;
use wish_app::{System, SystemContext};
use wish_core::{Diagnostic, Entity, Hash128, Result, Severity};
use wish_ecs::{ComponentId, EventId, ResourceId, World};
use wish_schema::wire::from_wire;
use wish_schema::{TypeKind, TypeSchema};
use wish_sdk::command::{Command, Target, decode_commands};
use wish_sdk::frame::{FrameWriter, query_layout};

use crate::engine::ScriptEngine;
use crate::module::{Live, ScriptModule};

/// What a type is to the world.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Role {
    /// Data attached to entities.
    Component,
    /// One value per world.
    Resource,
    /// A message between systems.
    Event,
}

/// A type the module uses.
#[derive(Clone, Debug, PartialEq)]
pub struct ModuleType {
    /// Component, resource or event.
    pub role: Role,
    /// Its schema, as the module describes it.
    pub schema: TypeSchema,
}

/// One column of a query parameter.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ColumnSpec {
    /// The component.
    pub component: String,
    /// Whether the system writes it.
    pub write: bool,
}

/// One parameter of a system, in order.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ParamSpec {
    /// `Query<…>`.
    Query {
        /// The components it reads or writes, in order.
        columns: Vec<ColumnSpec>,
        /// Components that must be present.
        with: Vec<String>,
        /// Components that must be absent.
        without: Vec<String>,
    },
    /// `Res<T>` or `ResMut<T>`.
    Res {
        /// The resource.
        resource: String,
        /// Whether it is `ResMut`.
        write: bool,
    },
    /// `EventReader<T>`.
    Events {
        /// The event type.
        event: String,
    },
    /// `EventWriter<T>`.
    Send {
        /// The event type.
        event: String,
    },
    /// `Commands`.
    Commands,
}

/// One system of the module.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SystemSpec {
    /// Its name.
    pub name: String,
    /// Systems it runs before.
    pub before: Vec<String>,
    /// Systems it runs after.
    pub after: Vec<String>,
    /// Its parameters, in order.
    pub params: Vec<ParamSpec>,
}

/// What a module says about itself.
#[derive(Clone, Debug, PartialEq)]
pub struct Manifest {
    /// The SDK version it was built with.
    pub sdk: String,
    /// Its types, in the order first used.
    pub types: Vec<ModuleType>,
    /// Its systems, in `export!` order.
    pub systems: Vec<SystemSpec>,
}

const MAX_SYSTEMS: usize = 256;
const MAX_TYPES: usize = 1024;
const MAX_PARAMS: usize = 32;
/// The most bytes one value of each of a module's types may take together:
/// every type gets a default value (and resources one in the world), so an
/// unbounded total would let a manifest exhaust memory (M5 WP9).
const MAX_TYPE_BYTES: u64 = 16 * 1024 * 1024;
/// The most commands one system call may give.
const MAX_COMMANDS: usize = 65_536;
/// The most entities a world may have for game code to spawn more: a
/// runaway or hostile module stops with a diagnostic instead of exhausting
/// memory.
pub const MAX_ENTITIES: usize = 1 << 22;
/// The most refused commands reported per call; the rest are counted.
const MAX_COMMAND_WARNINGS: usize = 8;

fn bad_manifest(name: &str, what: impl std::fmt::Display) -> Diagnostic {
    Diagnostic::error(
        "script_bad_manifest",
        format!("The manifest of '{name}' is malformed: {what}."),
        "Build game code with this engine's SDK (script_build); the manifest is generated by wish_sdk::export! and #[system].",
    )
    .at_file(name)
}

fn strings(value: Option<&Value>) -> Option<Vec<String>> {
    value?
        .as_array()?
        .iter()
        .map(|v| v.as_str().map(str::to_owned))
        .collect()
}

fn read_param(value: &Value) -> Option<ParamSpec> {
    if let Some(query) = value.get("query") {
        let columns = query
            .get("columns")?
            .as_array()?
            .iter()
            .map(|c| {
                Some(ColumnSpec {
                    component: c.get("type")?.as_str()?.to_owned(),
                    write: c.get("write")?.as_bool()?,
                })
            })
            .collect::<Option<Vec<_>>>()?;
        return Some(ParamSpec::Query {
            columns,
            with: strings(query.get("with"))?,
            without: strings(query.get("without"))?,
        });
    }
    if let Some(res) = value.get("res") {
        return Some(ParamSpec::Res {
            resource: res.get("type")?.as_str()?.to_owned(),
            write: res.get("write")?.as_bool()?,
        });
    }
    if let Some(events) = value.get("events") {
        return Some(ParamSpec::Events {
            event: events.get("type")?.as_str()?.to_owned(),
        });
    }
    if let Some(send) = value.get("send") {
        return Some(ParamSpec::Send {
            event: send.get("type")?.as_str()?.to_owned(),
        });
    }
    value.get("commands").map(|_| ParamSpec::Commands)
}

impl Manifest {
    /// Reads a manifest; `name` is the module, for diagnostics.
    pub fn parse(name: &str, text: &str) -> Result<Self> {
        let value: Value = serde_json::from_str(text).map_err(|e| bad_manifest(name, e))?;
        if value.get("abi").and_then(Value::as_i64) != Some(i64::from(crate::ABI_VERSION)) {
            return Err(bad_manifest(name, "its ABI version is not 1"));
        }
        let sdk = value
            .get("sdk")
            .and_then(Value::as_str)
            .unwrap_or("")
            .to_owned();
        let types_json = value
            .get("types")
            .and_then(Value::as_array)
            .ok_or_else(|| bad_manifest(name, "'types' is missing"))?;
        if types_json.len() > MAX_TYPES {
            return Err(bad_manifest(
                name,
                format!("it has more than {MAX_TYPES} types"),
            ));
        }
        let mut types = Vec::new();
        let mut total = 0u64;
        for entry in types_json {
            let role = match entry.get("role").and_then(Value::as_str) {
                Some("component") => Role::Component,
                Some("resource") => Role::Resource,
                Some("event") => Role::Event,
                _ => return Err(bad_manifest(name, "a type has no valid role")),
            };
            let schema = from_wire(entry.get("schema").unwrap_or(&Value::Null))
                .map_err(|e| e.at_file(name))?;
            if let Some(other) = types
                .iter()
                .find(|t: &&ModuleType| t.schema.name == schema.name)
            {
                let what = if other.role == role {
                    "with different fields"
                } else {
                    "with different roles"
                };
                return Err(Diagnostic::error(
                    "script_duplicate_type",
                    format!(
                        "'{name}' declares two types named '{}' ({what}).",
                        schema.name
                    ),
                    "Types are known by their name alone in the world, even in different Rust modules: rename one of them.",
                )
                .at_file(name));
            }
            total += u64::from(schema.size);
            if total > MAX_TYPE_BYTES {
                return Err(bad_manifest(
                    name,
                    format!(
                        "its types take more than {} MiB together",
                        MAX_TYPE_BYTES / (1024 * 1024)
                    ),
                ));
            }
            types.push(ModuleType { role, schema });
        }
        let systems_json = value
            .get("systems")
            .and_then(Value::as_array)
            .ok_or_else(|| bad_manifest(name, "'systems' is missing"))?;
        if systems_json.len() > MAX_SYSTEMS {
            return Err(bad_manifest(
                name,
                format!("it has more than {MAX_SYSTEMS} systems"),
            ));
        }
        let mut systems = Vec::new();
        let mut seen = BTreeSet::new();
        for entry in systems_json {
            let system_name = entry
                .get("name")
                .and_then(Value::as_str)
                .ok_or_else(|| bad_manifest(name, "a system has no name"))?
                .to_owned();
            if !seen.insert(system_name.clone()) {
                return Err(Diagnostic::error(
                    "script_duplicate_system",
                    format!("'{name}' lists the system '{system_name}' twice."),
                    "List each system once in wish_sdk::export!.",
                )
                .at_file(name));
            }
            let params_json = entry
                .get("params")
                .and_then(Value::as_array)
                .ok_or_else(|| {
                    bad_manifest(name, format!("system '{system_name}' has no params"))
                })?;
            if params_json.len() > MAX_PARAMS {
                return Err(bad_manifest(
                    name,
                    format!("system '{system_name}' has more than {MAX_PARAMS} parameters"),
                ));
            }
            let params = params_json
                .iter()
                .map(read_param)
                .collect::<Option<Vec<_>>>()
                .ok_or_else(|| {
                    bad_manifest(
                        name,
                        format!("a parameter of '{system_name}' is not understood"),
                    )
                })?;
            systems.push(SystemSpec {
                before: strings(entry.get("before")).unwrap_or_default(),
                after: strings(entry.get("after")).unwrap_or_default(),
                name: system_name,
                params,
            });
        }
        Ok(Self {
            sdk,
            types,
            systems,
        })
    }
}

/// A compiled game module and its manifest.
#[derive(Debug)]
pub struct GameModule {
    module: ScriptModule,
    manifest: Manifest,
}

impl GameModule {
    /// Compiles `bytes`, checks it and reads its manifest.
    pub fn load(engine: &ScriptEngine, name: &str, bytes: &[u8]) -> Result<Arc<Self>> {
        let module = ScriptModule::load(engine, name, bytes)?;
        let text = module.live()?.manifest()?;
        let manifest = Manifest::parse(name, &text)?;
        Ok(Arc::new(Self { module, manifest }))
    }

    /// The module's name (its file).
    pub fn name(&self) -> &str {
        self.module.name()
    }

    /// What the module says about itself.
    pub fn manifest(&self) -> &Manifest {
        &self.manifest
    }

    /// The hash of the module's bytes (ADR-005: "the same build").
    pub fn fingerprint(&self) -> Hash128 {
        self.module.fingerprint()
    }

    /// Registers the module's types in `world`. A type the world already
    /// has is checked: the engine's own types (`Transform`) must have
    /// exactly the engine's layout; a type the game declared earlier and has
    /// now changed (new code during a game) is moved to the new layout field
    /// by field, and a note says what was kept (`script_type_changed`).
    pub fn install(&self, world: &mut World) -> Result<Vec<Diagnostic>> {
        // Check everything first, so that a refusal changes nothing: an
        // engine type (bound to a Rust type) must match exactly.
        for ty in &self.manifest.types {
            let registry = world.registry();
            let name = ty.schema.name.as_str();
            let info = match ty.role {
                Role::Component => registry
                    .component_id(name)
                    .and_then(|id| registry.component(id)),
                Role::Resource => registry
                    .resource_id(name)
                    .and_then(|id| registry.resource(id)),
                Role::Event => registry.event_id(name).and_then(|id| registry.event(id)),
            };
            if let Some(info) = info
                && (info.is_native() || info.is_managed())
                && !info.schema().same_layout(&ty.schema)
            {
                return Err(Diagnostic::error(
                    "script_type_mismatch",
                    format!(
                        "'{}' describes the engine type '{name}' differently from the engine.",
                        self.name()
                    ),
                    "Rebuild the game code with this engine's SDK (script_build); if the game declares its own type with this name, rename it.",
                )
                .at_file(self.name()));
            }
        }
        let mut notes = Vec::new();
        for ty in &self.manifest.types {
            let name = ty.schema.name.as_str();
            let registry = world.registry();
            let existing = match ty.role {
                Role::Component => registry.component_id(name).and_then(|id| {
                    registry
                        .component(id)
                        .map(|info| (info.schema().clone(), info.is_native() || info.is_managed()))
                }),
                Role::Resource => registry.resource_id(name).and_then(|id| {
                    registry
                        .resource(id)
                        .map(|info| (info.schema().clone(), info.is_native() || info.is_managed()))
                }),
                Role::Event => registry.event_id(name).and_then(|id| {
                    registry
                        .event(id)
                        .map(|info| (info.schema().clone(), info.is_native() || info.is_managed()))
                }),
            };
            let result = match existing {
                // Nothing changed; or an engine type with the engine's layout
                // (its documentation is the engine's to keep).
                Some((schema, engine))
                    if schema == ty.schema || (engine && schema.same_layout(&ty.schema)) =>
                {
                    continue;
                }
                Some(_) => self.retype(world, ty).map(|note| notes.extend(note)),
                None => match ty.role {
                    Role::Component => world
                        .register_component_schema(ty.schema.clone())
                        .map(|_| ()),
                    Role::Resource => world
                        .register_resource_schema(ty.schema.clone())
                        .map(|_| ()),
                    Role::Event => world.register_event_schema(ty.schema.clone()).map(|_| ()),
                },
            };
            result.map_err(|cause| {
                Diagnostic::error(
                    "script_type_mismatch",
                    format!(
                        "'{}' describes '{name}' differently from the world: {}",
                        self.name(),
                        cause.message
                    ),
                    "If it is an engine type, rebuild the game code with this engine's SDK. If it is the game's own type, two declarations share the name: rename one.",
                )
                .at_file(self.name())
            })?;
        }
        // The game's resources exist from the start, at their defaults (a
        // scene that sets them, and the game itself, change them later), so
        // that tools and tests can read them before any system ran.
        for ty in self
            .manifest
            .types
            .iter()
            .filter(|t| t.role == Role::Resource)
        {
            let Some(id) = world.registry().resource_id(&ty.schema.name) else {
                continue;
            };
            if world.resource_bytes(id)?.is_none() {
                let default = world
                    .registry()
                    .resource(id)
                    .map(|info| info.default_bytes().to_vec())
                    .ok_or_else(poisoned)?;
                world.insert_resource_bytes(id, &default)?;
            }
        }
        Ok(notes)
    }

    /// Moves a changed game type to its new layout.
    fn retype(&self, world: &mut World, ty: &ModuleType) -> Result<Option<Diagnostic>> {
        let name = ty.schema.name.as_str();
        let registry = world.registry();
        let moved = match ty.role {
            Role::Component => {
                let id = registry.component_id(name).ok_or_else(poisoned)?;
                world.retype_component(id, ty.schema.clone())?
            }
            Role::Resource => {
                let id = registry.resource_id(name).ok_or_else(poisoned)?;
                world.retype_resource(id, ty.schema.clone())?
            }
            Role::Event => {
                let id = registry.event_id(name).ok_or_else(poisoned)?;
                world.retype_event(id, ty.schema.clone())?
            }
        };
        if moved.values == 0 && moved.dropped.is_empty() {
            return Ok(None);
        }
        let dropped = if moved.dropped.is_empty() {
            String::new()
        } else {
            format!(" Not kept: {}.", moved.dropped.join(", "))
        };
        Ok(Some(Diagnostic::info(
            "script_type_changed",
            format!(
                "'{name}' changed in the new code; {} value(s) were moved to its new fields.{dropped}",
                moved.values
            ),
            "Fields keep their values when the name stays and the value still fits; new fields start at their defaults. Rename a field back if a value was lost by mistake.",
        )))
    }
}

/// A message a system logged.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ScriptLog {
    /// The tick.
    pub tick: u64,
    /// The system.
    pub system: String,
    /// How serious.
    pub severity: Severity,
    /// The text.
    pub message: String,
}

/// The tick's instance, and which systems already ran in it.
#[derive(Default)]
struct Slot {
    live: Option<Live>,
    tick: u64,
    ran: BTreeSet<usize>,
    logs: Vec<ScriptLog>,
    floats: FloatCache,
}

/// One app's use of a module: the systems to add, and their shared state
/// (the tick's instance, the logs). Make one per app (session): two apps
/// never share an instance.
#[derive(Clone)]
pub struct ScriptRuntime {
    module: Arc<GameModule>,
    slot: Arc<Mutex<Slot>>,
    services: Option<Arc<dyn crate::host::HostServices>>,
}

impl std::fmt::Debug for ScriptRuntime {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ScriptRuntime")
            .field("module", &self.module.name())
            .finish_non_exhaustive()
    }
}

fn poisoned() -> Diagnostic {
    Diagnostic::error(
        "internal_error",
        "A game module's state was left inconsistent by an earlier failure.",
        "Reload the game module (script_build); report this if it happens again.",
    )
}

impl ScriptRuntime {
    /// A runtime for `module`.
    pub fn new(module: Arc<GameModule>) -> Self {
        Self {
            module,
            slot: Arc::new(Mutex::new(Slot::default())),
            services: None,
        }
    }

    /// Lets the module's systems ask the engine questions during a call
    /// (physics ray casts). Without services such questions get no answer.
    #[must_use]
    pub fn with_services(mut self, services: Arc<dyn crate::host::HostServices>) -> Self {
        self.services = Some(services);
        self
    }

    /// The module.
    pub fn module(&self) -> &Arc<GameModule> {
        &self.module
    }

    /// The module's systems, ready for `App::add_system`.
    pub fn systems(&self) -> Vec<System> {
        self.module
            .manifest
            .systems
            .iter()
            .enumerate()
            .map(|(index, spec)| {
                let runtime = self.clone();
                let mut system = System::dynamic(
                    &spec.name,
                    Arc::new(move |world: &mut World, context: &mut SystemContext<'_>| {
                        runtime.run(index, world, context)
                    }),
                );
                for other in &spec.before {
                    system = system.before(other);
                }
                for other in &spec.after {
                    system = system.after(other);
                }
                system
            })
            .collect()
    }

    /// What the systems logged since the last call, oldest first.
    pub fn take_logs(&self) -> Vec<ScriptLog> {
        self.slot
            .lock()
            .map(|mut slot| std::mem::take(&mut slot.logs))
            .unwrap_or_default()
    }

    fn run(&self, index: usize, world: &mut World, context: &mut SystemContext<'_>) -> Result<()> {
        let spec = self
            .module
            .manifest
            .systems
            .get(index)
            .ok_or_else(poisoned)?;
        let mut call = Call::build(world, spec, context)?;
        let mut slot = self.slot.lock().map_err(|_| poisoned())?;
        // A fresh instance per tick (ADR-025); a system running twice in the
        // "same" tick means the app went back (restore), so it starts over.
        if slot.live.is_none() || slot.tick != context.time.tick || slot.ran.contains(&index) {
            slot.live = Some(self.module.module.live()?);
            slot.tick = context.time.tick;
            slot.ran.clear();
        }
        slot.ran.insert(index);
        let Some(live) = slot.live.as_mut() else {
            return Err(poisoned());
        };
        let system = i32::try_from(index).map_err(|_| poisoned())?;
        let sent = call.frame.clone();
        // The world is lent to the call (texts, physics questions) and not
        // touched here until it returns.
        let query = Some(crate::host::QueryContext {
            world: crate::host::WorldRef::new(world),
            services: self.services.clone(),
        });
        let outcome = live.call(system, &mut call.frame, context.rng, query);
        let (report, commands) = match outcome {
            Ok(done) => done,
            Err(failure) => {
                slot.live = None;
                return Err(failure);
            }
        };
        for log in report.logs {
            slot.logs.push(ScriptLog {
                tick: context.time.tick,
                system: spec.name.clone(),
                severity: log.severity,
                message: log.message,
            });
        }
        let mut floats = std::mem::take(&mut slot.floats);
        drop(slot);
        let written = call.write_back(world, spec, &sent, &mut floats);
        let applied =
            written.and_then(|()| apply_commands(world, &spec.name, &commands, &mut floats));
        if let Ok(mut slot) = self.slot.lock() {
            slot.floats = floats;
        }
        let refused = applied?;
        if !refused.is_empty() {
            let mut slot = self.slot.lock().map_err(|_| poisoned())?;
            for message in refused {
                slot.logs.push(ScriptLog {
                    tick: context.time.tick,
                    system: spec.name.clone(),
                    severity: Severity::Warning,
                    message,
                });
            }
        }
        Ok(())
    }
}

/// Where one parameter's data is in the frame, resolved against the world.
enum Resolved {
    Query {
        /// The matching archetypes and how many entities each has, in the
        /// order their rows were packed.
        archetypes: Vec<(usize, usize)>,
        columns: Vec<(ComponentId, usize, bool)>,
    },
    Res {
        id: ResourceId,
        write: bool,
    },
    None,
}

/// One call's frame and how to read it back.
struct Call {
    frame: Vec<u8>,
    places: Vec<(usize, usize)>,
    resolved: Vec<Resolved>,
}

fn component(world: &World, name: &str, system: &str) -> Result<(ComponentId, usize)> {
    let id = world.component_id(name).map_err(|cause| {
        Diagnostic::error(
            "script_unknown_type",
            format!("System '{system}' uses the component '{name}', which the world does not have."),
            format!("Install the module's types first (the engine does this when it loads a module). {}", cause.hint),
        )
    })?;
    let size = world
        .registry()
        .component(id)
        .map(wish_ecs::TypeInfo::size)
        .ok_or_else(poisoned)?;
    Ok((id, size))
}

fn resource_id(world: &World, name: &str, system: &str) -> Result<ResourceId> {
    world.registry().resource_id(name).ok_or_else(|| {
        Diagnostic::error(
            "script_unknown_type",
            format!("System '{system}' uses the resource '{name}', which the world does not have."),
            "Install the module's types first (the engine does this when it loads a module).",
        )
    })
}

fn event_id(world: &World, name: &str, system: &str) -> Result<EventId> {
    world.registry().event_id(name).ok_or_else(|| {
        Diagnostic::error(
            "script_unknown_type",
            format!("System '{system}' uses the event '{name}', which the world does not have."),
            "Install the module's types first (the engine does this when it loads a module).",
        )
    })
}

/// The entities that have all of `required` and none of `excluded`, in the
/// world's stable order (archetypes in creation order, rows in order: the
/// same order native queries see).
fn matching(world: &World, required: &[ComponentId], excluded: &[ComponentId]) -> Vec<usize> {
    world
        .archetypes()
        .iter()
        .enumerate()
        .filter(|(_, a)| {
            !a.is_empty()
                && required.iter().all(|c| a.contains(*c))
                && !excluded.iter().any(|c| a.contains(*c))
        })
        .map(|(index, _)| index)
        .collect()
}

impl Call {
    fn build(world: &mut World, spec: &SystemSpec, context: &SystemContext<'_>) -> Result<Self> {
        let mut writer = FrameWriter::new();
        let mut resolved = Vec::with_capacity(spec.params.len());
        for param in &spec.params {
            match param {
                ParamSpec::Query {
                    columns,
                    with,
                    without,
                } => {
                    let mut cols = Vec::with_capacity(columns.len());
                    let mut required = Vec::new();
                    for column in columns {
                        let (id, size) = component(world, &column.component, &spec.name)?;
                        cols.push((id, size, column.write));
                        required.push(id);
                    }
                    for name in with {
                        required.push(component(world, name, &spec.name)?.0);
                    }
                    let excluded = without
                        .iter()
                        .map(|name| component(world, name, &spec.name).map(|(id, _)| id))
                        .collect::<Result<Vec<_>>>()?;
                    // Whole column slices, archetype by archetype: no
                    // per-entity lookups (M5 WP7).
                    let archetypes: Vec<(usize, usize)> = matching(world, &required, &excluded)
                        .into_iter()
                        .map(|a| (a, world.archetypes().get(a).map_or(0, |x| x.len())))
                        .collect();
                    let count: usize = archetypes.iter().map(|(_, n)| n).sum();
                    let sizes: Vec<usize> = cols.iter().map(|(_, size, _)| *size).collect();
                    let (len, offsets) = query_layout(count, &sizes);
                    let mut bytes = Vec::with_capacity(len);
                    bytes.extend((count as u32).to_le_bytes());
                    bytes.extend((cols.len() as u32).to_le_bytes());
                    for (a, _) in &archetypes {
                        for entity in world.archetypes().get(*a).map_or(&[][..], |x| x.entities()) {
                            bytes.extend(entity.to_bits().to_le_bytes());
                        }
                    }
                    for ((id, _, _), offset) in cols.iter().zip(&offsets) {
                        bytes.resize(*offset, 0);
                        for (a, _) in &archetypes {
                            world.archetype_column_bytes(*a, *id, &mut bytes)?;
                        }
                    }
                    bytes.resize(len, 0);
                    writer.section(bytes);
                    resolved.push(Resolved::Query {
                        archetypes,
                        columns: cols,
                    });
                }
                ParamSpec::Res { resource, write } => {
                    let id = resource_id(world, resource, &spec.name)?;
                    let bytes = match world.resource_bytes(id)? {
                        Some(bytes) => bytes,
                        None => {
                            // A resource nobody set yet starts at its default.
                            let default = world
                                .registry()
                                .resource(id)
                                .map(|info| info.default_bytes().to_vec())
                                .ok_or_else(poisoned)?;
                            world.insert_resource_bytes(id, &default)?;
                            default
                        }
                    };
                    writer.section(bytes);
                    resolved.push(Resolved::Res { id, write: *write });
                }
                ParamSpec::Events { event } => {
                    let id = event_id(world, event, &spec.name)?;
                    let events = world.event_bytes_since(id, context.last_run)?;
                    let size = world
                        .registry()
                        .event(id)
                        .map(wish_ecs::TypeInfo::size)
                        .ok_or_else(poisoned)?;
                    let mut bytes = vec![0u8; 8 + events.len() * size];
                    bytes[0..4].copy_from_slice(&(events.len() as u32).to_le_bytes());
                    for (row, event) in events.iter().enumerate() {
                        bytes[8 + row * size..8 + (row + 1) * size].copy_from_slice(event);
                    }
                    writer.section(bytes);
                    resolved.push(Resolved::None);
                }
                ParamSpec::Send { event } => {
                    event_id(world, event, &spec.name)?;
                    writer.section(Vec::new());
                    resolved.push(Resolved::None);
                }
                ParamSpec::Commands => {
                    writer.section(Vec::new());
                    resolved.push(Resolved::None);
                }
            }
        }
        let (frame, places) = writer.finish(context.time.tick);
        Ok(Self {
            frame,
            places,
            resolved,
        })
    }

    /// Writes back what the system changed. Only values that differ from
    /// what the system was given are written (so two parameters over the
    /// same data cannot undo each other), every one is checked first like
    /// any outside data, and nothing is written unless all of them pass.
    fn write_back(
        &self,
        world: &mut World,
        spec: &SystemSpec,
        sent: &[u8],
        floats: &mut FloatCache,
    ) -> Result<()> {
        enum Change {
            Rows {
                archetype: usize,
                id: ComponentId,
                size: usize,
                /// Where the archetype's rows start in the frame.
                at: usize,
                /// How many rows the archetype has.
                count: usize,
                /// The rows that changed.
                rows: Vec<u32>,
            },
            Resource {
                id: ResourceId,
                bytes: Vec<u8>,
            },
        }
        let mut changes = Vec::new();
        for (resolved, (start, len)) in self.resolved.iter().zip(&self.places) {
            let section = self.frame.get(*start..start + len).ok_or_else(poisoned)?;
            let before = sent.get(*start..start + len).ok_or_else(poisoned)?;
            if section == before {
                continue;
            }
            match resolved {
                Resolved::Query {
                    archetypes,
                    columns,
                } => {
                    let count: usize = archetypes.iter().map(|(_, n)| n).sum();
                    let sizes: Vec<usize> = columns.iter().map(|(_, size, _)| *size).collect();
                    let (_, offsets) = query_layout(count, &sizes);
                    for ((id, size, write), offset) in columns.iter().zip(&offsets) {
                        if !write || *size == 0 {
                            continue;
                        }
                        let info = world.registry().component(*id).ok_or_else(poisoned)?;
                        let layout = floats.of('c', info);
                        let mut at = *offset;
                        for (archetype, count) in archetypes {
                            let span = at..at + count * size;
                            let first = start + at;
                            at += count * size;
                            let new = section.get(span.clone()).ok_or_else(poisoned)?;
                            let old = before.get(span).ok_or_else(poisoned)?;
                            if new == old {
                                continue;
                            }
                            let mut rows = Vec::new();
                            for (row, (n, o)) in
                                new.chunks(*size).zip(old.chunks(*size)).enumerate()
                            {
                                if n != o {
                                    check_value(&layout, n, &spec.name, "wrote")?;
                                    rows.push(u32::try_from(row).map_err(|_| poisoned())?);
                                }
                            }
                            changes.push(Change::Rows {
                                archetype: *archetype,
                                id: *id,
                                size: *size,
                                at: first,
                                count: *count,
                                rows,
                            });
                        }
                    }
                }
                Resolved::Res { id, write: true } => {
                    let info = world.registry().resource(*id).ok_or_else(poisoned)?;
                    let layout = floats.of('r', info);
                    check_value(&layout, section, &spec.name, "wrote")?;
                    changes.push(Change::Resource {
                        id: *id,
                        bytes: section.to_vec(),
                    });
                }
                Resolved::Res { write: false, .. } | Resolved::None => {}
            }
        }
        // Everything was checked: now write, each change onto what the world
        // holds at that moment (an earlier parameter may have changed it).
        let mut column = Vec::new();
        for change in changes {
            match change {
                Change::Rows {
                    archetype,
                    id,
                    size,
                    at,
                    count,
                    rows,
                } => {
                    let new = self.frame.get(at..at + count * size).ok_or_else(poisoned)?;
                    let bytes = if rows.len() == count {
                        // Every row changed (the usual case for moving
                        // things): the frame's bytes are the column.
                        new
                    } else {
                        // Only some: the others keep what the world holds
                        // now (another parameter may have just changed them).
                        column.clear();
                        world.archetype_column_bytes(archetype, id, &mut column)?;
                        for row in rows {
                            let span = row as usize * size..(row as usize + 1) * size;
                            column
                                .get_mut(span.clone())
                                .ok_or_else(poisoned)?
                                .copy_from_slice(new.get(span).ok_or_else(poisoned)?);
                        }
                        &column
                    };
                    world
                        .write_archetype_column(archetype, id, bytes)
                        .map_err(|cause| write_failed(&spec.name, &cause))?;
                }
                Change::Resource { id, bytes } => {
                    if world.resource_bytes(id)?.as_deref() != Some(bytes.as_slice()) {
                        world
                            .insert_resource_bytes(id, &bytes)
                            .map_err(|cause| write_failed(&spec.name, &cause))?;
                    }
                }
            }
        }
        Ok(())
    }
}

/// A type as checks need it: its schema and where its floats are (an
/// offset with the top bit set is an `f64`).
struct Layout {
    schema: TypeSchema,
    floats: Vec<u32>,
}

/// Layouts worked out once per type for a runtime (a module's types change
/// only with a new module, which gets a new runtime): a schema can be large
/// (an array's default value), so it is never copied per call.
#[derive(Default)]
struct FloatCache {
    layouts: BTreeMap<String, Arc<Layout>>,
}

const WIDE: u32 = 1 << 31;

impl FloatCache {
    fn of(&mut self, role: char, info: &wish_ecs::TypeInfo) -> Arc<Layout> {
        let key = format!("{role}{}", info.schema().name);
        Arc::clone(self.layouts.entry(key).or_insert_with(|| {
            let schema = info.schema().clone();
            let mut floats = Vec::new();
            float_offsets(&schema, 0, &mut floats);
            Arc::new(Layout { schema, floats })
        }))
    }
}

/// The kind's floats: how many, and whether they are `f64`.
fn floats_of(kind: &TypeKind) -> Option<(usize, bool)> {
    match kind {
        TypeKind::F32 => Some((1, false)),
        TypeKind::F64 => Some((1, true)),
        TypeKind::Vec2 => Some((2, false)),
        TypeKind::Vec3 => Some((3, false)),
        TypeKind::Vec4 | TypeKind::Quat | TypeKind::Color => Some((4, false)),
        TypeKind::Mat4 => Some((16, false)),
        _ => None,
    }
}

/// Every float of `schema` (vectors, colours and matrices are packed
/// `f32`s), as offsets from `base`.
fn float_offsets(schema: &TypeSchema, base: usize, out: &mut Vec<u32>) {
    if let Some((count, wide)) = floats_of(&schema.kind) {
        let width = if wide { 8 } else { 4 };
        for n in 0..count {
            let offset = u32::try_from(base + n * width).unwrap_or(0);
            out.push(if wide { offset | WIDE } else { offset });
        }
        return;
    }
    match &schema.kind {
        TypeKind::Struct(fields) => {
            for field in fields {
                float_offsets(&field.ty, base + field.offset as usize, out);
            }
        }
        TypeKind::Array { element, len } if element.needs_floats() => {
            let size = element.size as usize;
            for n in 0..*len as usize {
                float_offsets(element, base + n * size, out);
            }
        }
        _ => {}
    }
}

trait NeedsFloats {
    fn needs_floats(&self) -> bool;
}

impl NeedsFloats for TypeSchema {
    fn needs_floats(&self) -> bool {
        floats_of(&self.kind).is_some()
            || match &self.kind {
                TypeKind::Struct(fields) => fields.iter().any(|f| f.ty.needs_floats()),
                TypeKind::Array { element, .. } => element.needs_floats(),
                _ => false,
            }
    }
}

/// The path of the float at `offset` (`Transform.translation[0]`), for
/// saying which one was not finite.
fn float_path(schema: &TypeSchema, offset: usize) -> String {
    fn find(schema: &TypeSchema, offset: usize, path: &mut String) {
        if let Some((count, wide)) = floats_of(&schema.kind) {
            if count > 1 {
                let width = if wide { 8 } else { 4 };
                path.push_str(&format!("[{}]", offset / width));
            }
            return;
        }
        match &schema.kind {
            TypeKind::Struct(fields) => {
                if let Some(field) = fields.iter().rev().find(|f| f.offset as usize <= offset) {
                    path.push('.');
                    path.push_str(&field.name);
                    find(&field.ty, offset - field.offset as usize, path);
                }
            }
            TypeKind::Array { element, .. } if element.size > 0 => {
                let size = element.size as usize;
                path.push_str(&format!("[{}]", offset / size));
                find(element, offset % size, path);
            }
            _ => {}
        }
    }
    let mut path = schema.name.clone();
    find(schema, offset, &mut path);
    path
}

/// Checks a value game code gives the world: its floats are finite, and
/// its bools and enums hold valid bytes. Nothing is stored if it fails.
fn check_value(layout: &Layout, bytes: &[u8], system: &str, verb: &str) -> Result<()> {
    let schema = &layout.schema;
    for &entry in &layout.floats {
        let offset = (entry & !WIDE) as usize;
        let finite = if entry & WIDE != 0 {
            bytes
                .get(offset..offset + 8)
                .and_then(|b| b.try_into().ok())
                .is_none_or(|b| f64::from_le_bytes(b).is_finite())
        } else {
            bytes
                .get(offset..offset + 4)
                .and_then(|b| b.try_into().ok())
                .is_none_or(|b| f32::from_le_bytes(b).is_finite())
        };
        if !finite {
            return Err(Diagnostic::error(
                "script_not_finite",
                format!(
                    "System '{system}' {verb} a value that is not a finite number into {}.",
                    float_path(schema, offset)
                ),
                "NaN and infinity usually come from dividing by zero or normalizing a zero-length vector; check with is_finite() (or guard the division) before writing. The value was not stored.",
            ));
        }
    }
    if schema.needs_validation() {
        wish_schema::json::validate_bytes(schema, bytes)
            .map_err(|cause| write_failed(system, &cause))?;
    }
    Ok(())
}

fn write_failed(system: &str, cause: &Diagnostic) -> Diagnostic {
    Diagnostic::error(
        "script_write_failed",
        format!(
            "System '{system}' wrote a value the engine cannot accept: {}",
            cause.message
        ),
        format!(
            "Values written through a query or ResMut are checked like any other input. {}",
            cause.hint
        ),
    )
}

fn command_failed(system: &str, index: usize, what: &str, cause: &str, hint: &str) -> Diagnostic {
    Diagnostic::error(
        "script_command_failed",
        format!("Command {index} of system '{system}' ({what}) failed: {cause}"),
        format!(
            "The commands before it were applied, as for a native system that fails midway. {hint}"
        ),
    )
}

/// The deepest hierarchy game code may build: each new link walks the
/// ancestors, so an unbounded chain would make every command slower.
pub const MAX_HIERARCHY_DEPTH: usize = 256;

/// The most bytes of component data the world may hold for game code to
/// add more: game code cannot exhaust the engine's memory.
pub const MAX_WORLD_BYTES: usize = 1 << 30;

/// The bytes of component data in `world` (rows times row size).
fn world_bytes(world: &World) -> usize {
    let registry = world.registry();
    world
        .archetypes()
        .iter()
        .map(|archetype| {
            let row: usize = archetype
                .components()
                .iter()
                .filter_map(|id| registry.component(*id).map(wish_ecs::TypeInfo::size))
                .sum();
            row.saturating_mul(archetype.len())
        })
        .fold(0usize, usize::saturating_add)
}

/// How deep `entity` is in the hierarchy (0 for a root), stopping at
/// [`MAX_HIERARCHY_DEPTH`].
fn depth(world: &World, entity: Entity) -> usize {
    let mut depth = 0;
    let mut at = entity;
    while let Some(parent) = world.parent(at) {
        depth += 1;
        if depth >= MAX_HIERARCHY_DEPTH {
            break;
        }
        at = parent;
    }
    depth
}

/// Applies a system's commands in order. A command that cannot be applied
/// is skipped and reported (returned as warning text), the way a native
/// command buffer skips it: commands are deferred, so their target may be
/// gone by the time they run. Despawning what is already gone is not even
/// reported (two players reaching the same coin). Commands that cannot be
/// decoded, too many commands, or a world that is full stop the system.
fn apply_commands(
    world: &mut World,
    system: &str,
    bytes: &[u8],
    floats: &mut FloatCache,
) -> Result<Vec<String>> {
    let mut refused = Vec::new();
    if bytes.is_empty() {
        return Ok(refused);
    }
    let commands = decode_commands(bytes, MAX_COMMANDS).map_err(|cause| {
        command_failed(
            system,
            0,
            "decoding",
            &cause,
            "Rebuild the game code with this engine's SDK; a system gives at most 65536 commands per call.",
        )
    })?;
    let mut size = world_bytes(world);
    let full = |index: usize, what: &str| {
        command_failed(
            system,
            index,
            what,
            &format!(
                "the world already holds {} MiB of component data, the most game code may fill",
                MAX_WORLD_BYTES >> 20
            ),
            "A system that adds data every tick without removing any grows the world for ever; despawn what is no longer needed.",
        )
    };
    let mut skipped = 0usize;
    let mut spawned: Vec<Option<Entity>> = Vec::new();
    for (index, command) in commands.iter().enumerate() {
        let resolve = |target: Target, spawned: &[Option<Entity>]| -> Result<Entity> {
            match target {
                Target::Existing(entity) => Ok(entity),
                Target::New(n) => spawned.get(n as usize).copied().flatten().ok_or_else(|| {
                    Diagnostic::error(
                        "spawn_target_missing",
                        format!("it names new entity {n}, which was not spawned in this call"),
                        "Spawn before using the new entity.",
                    )
                }),
            }
        };
        let result: Result<()> = match command {
            Command::Spawn { .. } => {
                if world.entity_count() >= MAX_ENTITIES {
                    return Err(command_failed(
                        system,
                        index,
                        "spawn",
                        &format!("the world already has {MAX_ENTITIES} entities, the most game code may create"),
                        "A system that spawns every tick without despawning grows the world for ever; despawn what is no longer needed.",
                    ));
                }
                let entity = world.spawn()?;
                spawned.push(Some(entity));
                Ok(())
            }
            Command::Despawn(target) => resolve(*target, &spawned).and_then(|entity| {
                if world.contains(entity) {
                    world.despawn(entity)
                } else {
                    Ok(())
                }
            }),
            Command::Insert {
                target,
                component: name,
                bytes,
            } => {
                if size.saturating_add(bytes.len()) > MAX_WORLD_BYTES {
                    return Err(full(index, &format!("insert {name}")));
                }
                resolve(*target, &spawned).and_then(|entity| {
                    let (id, expected) = component(world, name, system)?;
                    if bytes.len() != expected {
                        return Err(Diagnostic::error(
                            "script_value_size",
                            format!(
                                "the value has {} bytes, '{name}' takes {expected}",
                                bytes.len()
                            ),
                            "Rebuild the game code with this engine's SDK.",
                        ));
                    }
                    let info = world.registry().component(id).ok_or_else(poisoned)?;
                    let layout = floats.of('c', info);
                    check_value(&layout, bytes, system, "inserted")?;
                    world.insert_bytes(entity, id, bytes)?;
                    size = size.saturating_add(bytes.len());
                    Ok(())
                })
            }
            Command::Remove {
                target,
                component: name,
            } => resolve(*target, &spawned).and_then(|entity| {
                let (id, _) = component(world, name, system)?;
                world.remove_by_id(entity, id).map(|_| ())
            }),
            Command::Send { event, bytes } => event_id(world, event, system).and_then(|id| {
                let info = world.registry().event(id).ok_or_else(poisoned)?;
                // The size first: a wrong size costs nothing more.
                if bytes.len() == info.size() {
                    let layout = floats.of('e', info);
                    check_value(&layout, bytes, system, "sent")?;
                }
                world.send_bytes(id, bytes)
            }),
            Command::SetParent { child, parent } => resolve(*child, &spawned).and_then(|child| {
                let parent = resolve(*parent, &spawned)?;
                if world.contains(parent) && depth(world, parent) + 1 >= MAX_HIERARCHY_DEPTH {
                    return Err(Diagnostic::error(
                        "hierarchy_too_deep",
                        format!(
                            "the hierarchy would be deeper than {MAX_HIERARCHY_DEPTH} levels"
                        ),
                        "Attach to an entity nearer the root; a chain this deep is usually a parent set every tick by mistake.",
                    ));
                }
                world.set_parent(child, parent)
            }),
            Command::RemoveParent(child) => {
                resolve(*child, &spawned).and_then(|child| world.remove_parent(child))
            }
        };
        if let Err(cause) = result {
            if refused.len() < MAX_COMMAND_WARNINGS {
                let what = describe(command);
                refused.push(format!(
                    "[script_command_failed] Command {index} of system '{system}' ({what}) was skipped: {} {}",
                    cause.message, cause.hint
                ));
            } else {
                skipped += 1;
            }
        }
    }
    if skipped > 0 {
        refused.push(format!(
            "[script_command_failed] {skipped} more commands of system '{system}' were skipped."
        ));
    }
    Ok(refused)
}

/// A command, in a few words.
fn describe(command: &Command) -> String {
    match command {
        Command::Spawn { .. } => "spawn".to_owned(),
        Command::Despawn(_) => "despawn".to_owned(),
        Command::Insert { component, .. } => format!("insert {component}"),
        Command::Remove { component, .. } => format!("remove {component}"),
        Command::Send { event, .. } => format!("send {event}"),
        Command::SetParent { .. } => "set_parent".to_owned(),
        Command::RemoveParent(_) => "remove_parent".to_owned(),
    }
}
