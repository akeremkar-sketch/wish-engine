//! A game module in a world: its manifest, its types, its systems.
//!
//! [`GameModule::load`] compiles a module and reads its manifest (types and
//! systems, design note M5 §3). [`GameModule::install`] registers the
//! module's types in a world (the engine's own types must match the
//! engine's declarations exactly). [`ScriptRuntime::systems`] gives the
//! systems to add to an app: each call builds the frame from the world,
//! runs the system in the tick's instance, writes back what changed and
//! applies the commands.

use std::collections::BTreeSet;
use std::sync::{Arc, Mutex};

use serde_json::Value;
use wish_app::{System, SystemContext};
use wish_core::{Diagnostic, Entity, Hash128, Result, Severity};
use wish_ecs::{ComponentId, EventId, ResourceId, World};
use wish_schema::TypeSchema;
use wish_schema::wire::from_wire;
use wish_sdk::command::{Command, Target, decode_commands};
use wish_sdk::frame::{FrameWriter, query_layout};

use crate::engine::ScriptEngine;
use crate::module::{Live, ScriptModule};

/// What a type is to the world.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Role {
    /// Data attached to entities.
    Component,
    /// One value per world.
    Resource,
    /// A message between systems.
    Event,
}

/// A type the module uses.
#[derive(Clone, Debug, PartialEq)]
pub struct ModuleType {
    /// Component, resource or event.
    pub role: Role,
    /// Its schema, as the module describes it.
    pub schema: TypeSchema,
}

/// One column of a query parameter.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ColumnSpec {
    /// The component.
    pub component: String,
    /// Whether the system writes it.
    pub write: bool,
}

/// One parameter of a system, in order.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ParamSpec {
    /// `Query<…>`.
    Query {
        /// The components it reads or writes, in order.
        columns: Vec<ColumnSpec>,
        /// Components that must be present.
        with: Vec<String>,
        /// Components that must be absent.
        without: Vec<String>,
    },
    /// `Res<T>` or `ResMut<T>`.
    Res {
        /// The resource.
        resource: String,
        /// Whether it is `ResMut`.
        write: bool,
    },
    /// `EventReader<T>`.
    Events {
        /// The event type.
        event: String,
    },
    /// `EventWriter<T>`.
    Send {
        /// The event type.
        event: String,
    },
    /// `Commands`.
    Commands,
}

/// One system of the module.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SystemSpec {
    /// Its name.
    pub name: String,
    /// Systems it runs before.
    pub before: Vec<String>,
    /// Systems it runs after.
    pub after: Vec<String>,
    /// Its parameters, in order.
    pub params: Vec<ParamSpec>,
}

/// What a module says about itself.
#[derive(Clone, Debug, PartialEq)]
pub struct Manifest {
    /// The SDK version it was built with.
    pub sdk: String,
    /// Its types, in the order first used.
    pub types: Vec<ModuleType>,
    /// Its systems, in `export!` order.
    pub systems: Vec<SystemSpec>,
}

const MAX_SYSTEMS: usize = 256;
const MAX_TYPES: usize = 1024;
const MAX_PARAMS: usize = 32;

fn bad_manifest(name: &str, what: impl std::fmt::Display) -> Diagnostic {
    Diagnostic::error(
        "script_bad_manifest",
        format!("The manifest of '{name}' is malformed: {what}."),
        "Build game code with this engine's SDK (script_build); the manifest is generated by wish_sdk::export! and #[system].",
    )
    .at_file(name)
}

fn strings(value: Option<&Value>) -> Option<Vec<String>> {
    value?
        .as_array()?
        .iter()
        .map(|v| v.as_str().map(str::to_owned))
        .collect()
}

fn read_param(value: &Value) -> Option<ParamSpec> {
    if let Some(query) = value.get("query") {
        let columns = query
            .get("columns")?
            .as_array()?
            .iter()
            .map(|c| {
                Some(ColumnSpec {
                    component: c.get("type")?.as_str()?.to_owned(),
                    write: c.get("write")?.as_bool()?,
                })
            })
            .collect::<Option<Vec<_>>>()?;
        return Some(ParamSpec::Query {
            columns,
            with: strings(query.get("with"))?,
            without: strings(query.get("without"))?,
        });
    }
    if let Some(res) = value.get("res") {
        return Some(ParamSpec::Res {
            resource: res.get("type")?.as_str()?.to_owned(),
            write: res.get("write")?.as_bool()?,
        });
    }
    if let Some(events) = value.get("events") {
        return Some(ParamSpec::Events {
            event: events.get("type")?.as_str()?.to_owned(),
        });
    }
    if let Some(send) = value.get("send") {
        return Some(ParamSpec::Send {
            event: send.get("type")?.as_str()?.to_owned(),
        });
    }
    value.get("commands").map(|_| ParamSpec::Commands)
}

impl Manifest {
    /// Reads a manifest; `name` is the module, for diagnostics.
    pub fn parse(name: &str, text: &str) -> Result<Self> {
        let value: Value = serde_json::from_str(text).map_err(|e| bad_manifest(name, e))?;
        if value.get("abi").and_then(Value::as_i64) != Some(i64::from(crate::ABI_VERSION)) {
            return Err(bad_manifest(name, "its ABI version is not 1"));
        }
        let sdk = value
            .get("sdk")
            .and_then(Value::as_str)
            .unwrap_or("")
            .to_owned();
        let types_json = value
            .get("types")
            .and_then(Value::as_array)
            .ok_or_else(|| bad_manifest(name, "'types' is missing"))?;
        if types_json.len() > MAX_TYPES {
            return Err(bad_manifest(
                name,
                format!("it has more than {MAX_TYPES} types"),
            ));
        }
        let mut types = Vec::new();
        for entry in types_json {
            let role = match entry.get("role").and_then(Value::as_str) {
                Some("component") => Role::Component,
                Some("resource") => Role::Resource,
                Some("event") => Role::Event,
                _ => return Err(bad_manifest(name, "a type has no valid role")),
            };
            let schema = from_wire(entry.get("schema").unwrap_or(&Value::Null))
                .map_err(|e| e.at_file(name))?;
            types.push(ModuleType { role, schema });
        }
        let systems_json = value
            .get("systems")
            .and_then(Value::as_array)
            .ok_or_else(|| bad_manifest(name, "'systems' is missing"))?;
        if systems_json.len() > MAX_SYSTEMS {
            return Err(bad_manifest(
                name,
                format!("it has more than {MAX_SYSTEMS} systems"),
            ));
        }
        let mut systems = Vec::new();
        let mut seen = BTreeSet::new();
        for entry in systems_json {
            let system_name = entry
                .get("name")
                .and_then(Value::as_str)
                .ok_or_else(|| bad_manifest(name, "a system has no name"))?
                .to_owned();
            if !seen.insert(system_name.clone()) {
                return Err(Diagnostic::error(
                    "script_duplicate_system",
                    format!("'{name}' lists the system '{system_name}' twice."),
                    "List each system once in wish_sdk::export!.",
                )
                .at_file(name));
            }
            let params_json = entry
                .get("params")
                .and_then(Value::as_array)
                .ok_or_else(|| {
                    bad_manifest(name, format!("system '{system_name}' has no params"))
                })?;
            if params_json.len() > MAX_PARAMS {
                return Err(bad_manifest(
                    name,
                    format!("system '{system_name}' has more than {MAX_PARAMS} parameters"),
                ));
            }
            let params = params_json
                .iter()
                .map(read_param)
                .collect::<Option<Vec<_>>>()
                .ok_or_else(|| {
                    bad_manifest(
                        name,
                        format!("a parameter of '{system_name}' is not understood"),
                    )
                })?;
            systems.push(SystemSpec {
                before: strings(entry.get("before")).unwrap_or_default(),
                after: strings(entry.get("after")).unwrap_or_default(),
                name: system_name,
                params,
            });
        }
        Ok(Self {
            sdk,
            types,
            systems,
        })
    }
}

/// A compiled game module and its manifest.
#[derive(Debug)]
pub struct GameModule {
    module: ScriptModule,
    manifest: Manifest,
}

impl GameModule {
    /// Compiles `bytes`, checks it and reads its manifest.
    pub fn load(engine: &ScriptEngine, name: &str, bytes: &[u8]) -> Result<Arc<Self>> {
        let module = ScriptModule::load(engine, name, bytes)?;
        let text = module.live()?.manifest()?;
        let manifest = Manifest::parse(name, &text)?;
        Ok(Arc::new(Self { module, manifest }))
    }

    /// The module's name (its file).
    pub fn name(&self) -> &str {
        self.module.name()
    }

    /// What the module says about itself.
    pub fn manifest(&self) -> &Manifest {
        &self.manifest
    }

    /// The hash of the module's bytes (ADR-005: "the same build").
    pub fn fingerprint(&self) -> Hash128 {
        self.module.fingerprint()
    }

    /// Registers the module's types in `world`. A type the world already
    /// has is checked: the engine's own types (`Transform`) must have
    /// exactly the engine's layout; a type the game declared earlier and has
    /// now changed (new code during a game) is moved to the new layout field
    /// by field, and a note says what was kept (`script_type_changed`).
    pub fn install(&self, world: &mut World) -> Result<Vec<Diagnostic>> {
        // Check everything first, so that a refusal changes nothing: an
        // engine type (bound to a Rust type) must match exactly.
        for ty in &self.manifest.types {
            let registry = world.registry();
            let name = ty.schema.name.as_str();
            let info = match ty.role {
                Role::Component => registry
                    .component_id(name)
                    .and_then(|id| registry.component(id)),
                Role::Resource => registry
                    .resource_id(name)
                    .and_then(|id| registry.resource(id)),
                Role::Event => registry.event_id(name).and_then(|id| registry.event(id)),
            };
            if let Some(info) = info
                && (info.is_native() || info.is_managed())
                && !info.schema().same_layout(&ty.schema)
            {
                return Err(Diagnostic::error(
                    "script_type_mismatch",
                    format!(
                        "'{}' describes the engine type '{name}' differently from the engine.",
                        self.name()
                    ),
                    "Rebuild the game code with this engine's SDK (script_build); if the game declares its own type with this name, rename it.",
                )
                .at_file(self.name()));
            }
        }
        let mut notes = Vec::new();
        for ty in &self.manifest.types {
            let name = ty.schema.name.as_str();
            let registry = world.registry();
            let existing = match ty.role {
                Role::Component => registry.component_id(name).and_then(|id| {
                    registry
                        .component(id)
                        .map(|info| (info.schema().clone(), info.is_native() || info.is_managed()))
                }),
                Role::Resource => registry.resource_id(name).and_then(|id| {
                    registry
                        .resource(id)
                        .map(|info| (info.schema().clone(), info.is_native() || info.is_managed()))
                }),
                Role::Event => registry.event_id(name).and_then(|id| {
                    registry
                        .event(id)
                        .map(|info| (info.schema().clone(), info.is_native() || info.is_managed()))
                }),
            };
            let result = match existing {
                // Nothing changed; or an engine type with the engine's layout
                // (its documentation is the engine's to keep).
                Some((schema, engine))
                    if schema == ty.schema || (engine && schema.same_layout(&ty.schema)) =>
                {
                    continue;
                }
                Some(_) => self.retype(world, ty).map(|note| notes.extend(note)),
                None => match ty.role {
                    Role::Component => world
                        .register_component_schema(ty.schema.clone())
                        .map(|_| ()),
                    Role::Resource => world
                        .register_resource_schema(ty.schema.clone())
                        .map(|_| ()),
                    Role::Event => world.register_event_schema(ty.schema.clone()).map(|_| ()),
                },
            };
            result.map_err(|cause| {
                Diagnostic::error(
                    "script_type_mismatch",
                    format!(
                        "'{}' describes '{name}' differently from the world: {}",
                        self.name(),
                        cause.message
                    ),
                    "If it is an engine type, rebuild the game code with this engine's SDK. If it is the game's own type, two declarations share the name: rename one.",
                )
                .at_file(self.name())
            })?;
        }
        // The game's resources exist from the start, at their defaults (a
        // scene that sets them, and the game itself, change them later), so
        // that tools and tests can read them before any system ran.
        for ty in self
            .manifest
            .types
            .iter()
            .filter(|t| t.role == Role::Resource)
        {
            let Some(id) = world.registry().resource_id(&ty.schema.name) else {
                continue;
            };
            if world.resource_bytes(id)?.is_none() {
                let default = world
                    .registry()
                    .resource(id)
                    .map(|info| info.default_bytes().to_vec())
                    .ok_or_else(poisoned)?;
                world.insert_resource_bytes(id, &default)?;
            }
        }
        Ok(notes)
    }

    /// Moves a changed game type to its new layout.
    fn retype(&self, world: &mut World, ty: &ModuleType) -> Result<Option<Diagnostic>> {
        let name = ty.schema.name.as_str();
        let registry = world.registry();
        let moved = match ty.role {
            Role::Component => {
                let id = registry.component_id(name).ok_or_else(poisoned)?;
                world.retype_component(id, ty.schema.clone())?
            }
            Role::Resource => {
                let id = registry.resource_id(name).ok_or_else(poisoned)?;
                world.retype_resource(id, ty.schema.clone())?
            }
            Role::Event => {
                let id = registry.event_id(name).ok_or_else(poisoned)?;
                world.retype_event(id, ty.schema.clone())?
            }
        };
        if moved.values == 0 && moved.dropped.is_empty() {
            return Ok(None);
        }
        let dropped = if moved.dropped.is_empty() {
            String::new()
        } else {
            format!(" Not kept: {}.", moved.dropped.join(", "))
        };
        Ok(Some(Diagnostic::info(
            "script_type_changed",
            format!(
                "'{name}' changed in the new code; {} value(s) were moved to its new fields.{dropped}",
                moved.values
            ),
            "Fields keep their values when the name stays and the value still fits; new fields start at their defaults. Rename a field back if a value was lost by mistake.",
        )))
    }
}

/// A message a system logged.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ScriptLog {
    /// The tick.
    pub tick: u64,
    /// The system.
    pub system: String,
    /// How serious.
    pub severity: Severity,
    /// The text.
    pub message: String,
}

/// The tick's instance, and which systems already ran in it.
#[derive(Default)]
struct Slot {
    live: Option<Live>,
    tick: u64,
    ran: BTreeSet<usize>,
    logs: Vec<ScriptLog>,
}

/// One app's use of a module: the systems to add, and their shared state
/// (the tick's instance, the logs). Make one per app (session): two apps
/// never share an instance.
#[derive(Clone)]
pub struct ScriptRuntime {
    module: Arc<GameModule>,
    slot: Arc<Mutex<Slot>>,
}

impl std::fmt::Debug for ScriptRuntime {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ScriptRuntime")
            .field("module", &self.module.name())
            .finish_non_exhaustive()
    }
}

fn poisoned() -> Diagnostic {
    Diagnostic::error(
        "internal_error",
        "A game module's state was left inconsistent by an earlier failure.",
        "Reload the game module (script_build); report this if it happens again.",
    )
}

impl ScriptRuntime {
    /// A runtime for `module`.
    pub fn new(module: Arc<GameModule>) -> Self {
        Self {
            module,
            slot: Arc::new(Mutex::new(Slot::default())),
        }
    }

    /// The module.
    pub fn module(&self) -> &Arc<GameModule> {
        &self.module
    }

    /// The module's systems, ready for `App::add_system`.
    pub fn systems(&self) -> Vec<System> {
        self.module
            .manifest
            .systems
            .iter()
            .enumerate()
            .map(|(index, spec)| {
                let runtime = self.clone();
                let mut system = System::dynamic(
                    &spec.name,
                    Arc::new(move |world: &mut World, context: &mut SystemContext<'_>| {
                        runtime.run(index, world, context)
                    }),
                );
                for other in &spec.before {
                    system = system.before(other);
                }
                for other in &spec.after {
                    system = system.after(other);
                }
                system
            })
            .collect()
    }

    /// What the systems logged since the last call, oldest first.
    pub fn take_logs(&self) -> Vec<ScriptLog> {
        self.slot
            .lock()
            .map(|mut slot| std::mem::take(&mut slot.logs))
            .unwrap_or_default()
    }

    fn run(&self, index: usize, world: &mut World, context: &mut SystemContext<'_>) -> Result<()> {
        let spec = self
            .module
            .manifest
            .systems
            .get(index)
            .ok_or_else(poisoned)?;
        let mut call = Call::build(world, spec, context)?;
        let mut slot = self.slot.lock().map_err(|_| poisoned())?;
        // A fresh instance per tick (ADR-025); a system running twice in the
        // "same" tick means the app went back (restore), so it starts over.
        if slot.live.is_none() || slot.tick != context.time.tick || slot.ran.contains(&index) {
            slot.live = Some(self.module.module.live()?);
            slot.tick = context.time.tick;
            slot.ran.clear();
        }
        slot.ran.insert(index);
        let Some(live) = slot.live.as_mut() else {
            return Err(poisoned());
        };
        let system = i32::try_from(index).map_err(|_| poisoned())?;
        let outcome = live.call(system, &mut call.frame, context.rng);
        let (report, commands) = match outcome {
            Ok(done) => done,
            Err(failure) => {
                slot.live = None;
                return Err(failure);
            }
        };
        for log in report.logs {
            slot.logs.push(ScriptLog {
                tick: context.time.tick,
                system: spec.name.clone(),
                severity: log.severity,
                message: log.message,
            });
        }
        drop(slot);
        call.write_back(world, spec)?;
        apply_commands(world, &spec.name, &commands)
    }
}

/// Where one parameter's data is in the frame, resolved against the world.
enum Resolved {
    Query {
        /// The matching archetypes and how many entities each has, in the
        /// order their rows were packed.
        archetypes: Vec<(usize, usize)>,
        columns: Vec<(ComponentId, usize, bool)>,
    },
    Res {
        id: ResourceId,
        write: bool,
    },
    None,
}

/// One call's frame and how to read it back.
struct Call {
    frame: Vec<u8>,
    places: Vec<(usize, usize)>,
    resolved: Vec<Resolved>,
}

fn component(world: &World, name: &str, system: &str) -> Result<(ComponentId, usize)> {
    let id = world.component_id(name).map_err(|cause| {
        Diagnostic::error(
            "script_unknown_type",
            format!("System '{system}' uses the component '{name}', which the world does not have."),
            format!("Install the module's types first (the engine does this when it loads a module). {}", cause.hint),
        )
    })?;
    let size = world
        .registry()
        .component(id)
        .map(wish_ecs::TypeInfo::size)
        .ok_or_else(poisoned)?;
    Ok((id, size))
}

fn resource_id(world: &World, name: &str, system: &str) -> Result<ResourceId> {
    world.registry().resource_id(name).ok_or_else(|| {
        Diagnostic::error(
            "script_unknown_type",
            format!("System '{system}' uses the resource '{name}', which the world does not have."),
            "Install the module's types first (the engine does this when it loads a module).",
        )
    })
}

fn event_id(world: &World, name: &str, system: &str) -> Result<EventId> {
    world.registry().event_id(name).ok_or_else(|| {
        Diagnostic::error(
            "script_unknown_type",
            format!("System '{system}' uses the event '{name}', which the world does not have."),
            "Install the module's types first (the engine does this when it loads a module).",
        )
    })
}

/// The entities that have all of `required` and none of `excluded`, in the
/// world's stable order (archetypes in creation order, rows in order: the
/// same order native queries see).
fn matching(world: &World, required: &[ComponentId], excluded: &[ComponentId]) -> Vec<usize> {
    world
        .archetypes()
        .iter()
        .enumerate()
        .filter(|(_, a)| {
            !a.is_empty()
                && required.iter().all(|c| a.contains(*c))
                && !excluded.iter().any(|c| a.contains(*c))
        })
        .map(|(index, _)| index)
        .collect()
}

impl Call {
    fn build(world: &mut World, spec: &SystemSpec, context: &SystemContext<'_>) -> Result<Self> {
        let mut writer = FrameWriter::new();
        let mut resolved = Vec::with_capacity(spec.params.len());
        for param in &spec.params {
            match param {
                ParamSpec::Query {
                    columns,
                    with,
                    without,
                } => {
                    let mut cols = Vec::with_capacity(columns.len());
                    let mut required = Vec::new();
                    for column in columns {
                        let (id, size) = component(world, &column.component, &spec.name)?;
                        cols.push((id, size, column.write));
                        required.push(id);
                    }
                    for name in with {
                        required.push(component(world, name, &spec.name)?.0);
                    }
                    let excluded = without
                        .iter()
                        .map(|name| component(world, name, &spec.name).map(|(id, _)| id))
                        .collect::<Result<Vec<_>>>()?;
                    // Whole column slices, archetype by archetype: no
                    // per-entity lookups (M5 WP7).
                    let archetypes: Vec<(usize, usize)> = matching(world, &required, &excluded)
                        .into_iter()
                        .map(|a| (a, world.archetypes().get(a).map_or(0, |x| x.len())))
                        .collect();
                    let count: usize = archetypes.iter().map(|(_, n)| n).sum();
                    let sizes: Vec<usize> = cols.iter().map(|(_, size, _)| *size).collect();
                    let (len, offsets) = query_layout(count, &sizes);
                    let mut bytes = Vec::with_capacity(len);
                    bytes.extend((count as u32).to_le_bytes());
                    bytes.extend((cols.len() as u32).to_le_bytes());
                    for (a, _) in &archetypes {
                        for entity in world.archetypes().get(*a).map_or(&[][..], |x| x.entities()) {
                            bytes.extend(entity.to_bits().to_le_bytes());
                        }
                    }
                    for ((id, _, _), offset) in cols.iter().zip(&offsets) {
                        bytes.resize(*offset, 0);
                        for (a, _) in &archetypes {
                            world.archetype_column_bytes(*a, *id, &mut bytes)?;
                        }
                    }
                    bytes.resize(len, 0);
                    writer.section(bytes);
                    resolved.push(Resolved::Query {
                        archetypes,
                        columns: cols,
                    });
                }
                ParamSpec::Res { resource, write } => {
                    let id = resource_id(world, resource, &spec.name)?;
                    let bytes = match world.resource_bytes(id)? {
                        Some(bytes) => bytes,
                        None => {
                            // A resource nobody set yet starts at its default.
                            let default = world
                                .registry()
                                .resource(id)
                                .map(|info| info.default_bytes().to_vec())
                                .ok_or_else(poisoned)?;
                            world.insert_resource_bytes(id, &default)?;
                            default
                        }
                    };
                    writer.section(bytes);
                    resolved.push(Resolved::Res { id, write: *write });
                }
                ParamSpec::Events { event } => {
                    let id = event_id(world, event, &spec.name)?;
                    let events = world.event_bytes_since(id, context.last_run)?;
                    let size = world
                        .registry()
                        .event(id)
                        .map(wish_ecs::TypeInfo::size)
                        .ok_or_else(poisoned)?;
                    let mut bytes = vec![0u8; 8 + events.len() * size];
                    bytes[0..4].copy_from_slice(&(events.len() as u32).to_le_bytes());
                    for (row, event) in events.iter().enumerate() {
                        bytes[8 + row * size..8 + (row + 1) * size].copy_from_slice(event);
                    }
                    writer.section(bytes);
                    resolved.push(Resolved::None);
                }
                ParamSpec::Send { event } => {
                    event_id(world, event, &spec.name)?;
                    writer.section(Vec::new());
                    resolved.push(Resolved::None);
                }
                ParamSpec::Commands => {
                    writer.section(Vec::new());
                    resolved.push(Resolved::None);
                }
            }
        }
        let (frame, places) = writer.finish(context.time.tick);
        Ok(Self {
            frame,
            places,
            resolved,
        })
    }

    /// Writes back what the system changed. Values are compared first, so
    /// only real changes count as changes (change detection stays honest),
    /// and every written value is checked like any outside data.
    fn write_back(&self, world: &mut World, spec: &SystemSpec) -> Result<()> {
        for ((resolved, (start, len)), _) in
            self.resolved.iter().zip(&self.places).zip(&spec.params)
        {
            let section = self.frame.get(*start..start + len).ok_or_else(poisoned)?;
            match resolved {
                Resolved::Query {
                    archetypes,
                    columns,
                } => {
                    let count: usize = archetypes.iter().map(|(_, n)| n).sum();
                    let sizes: Vec<usize> = columns.iter().map(|(_, size, _)| *size).collect();
                    let (_, offsets) = query_layout(count, &sizes);
                    for ((id, size, write), offset) in columns.iter().zip(&offsets) {
                        if !write {
                            continue;
                        }
                        let mut at = *offset;
                        for (a, rows) in archetypes {
                            let slice = section.get(at..at + rows * size).ok_or_else(poisoned)?;
                            world
                                .write_archetype_column(*a, *id, slice)
                                .map_err(|cause| write_failed(&spec.name, &cause))?;
                            at += rows * size;
                        }
                    }
                }
                Resolved::Res { id, write: true } => {
                    if world.resource_bytes(*id)?.as_deref() != Some(section) {
                        world
                            .insert_resource_bytes(*id, section)
                            .map_err(|cause| write_failed(&spec.name, &cause))?;
                    }
                }
                Resolved::Res { write: false, .. } | Resolved::None => {}
            }
        }
        Ok(())
    }
}

fn write_failed(system: &str, cause: &Diagnostic) -> Diagnostic {
    Diagnostic::error(
        "script_write_failed",
        format!(
            "System '{system}' wrote a value the engine cannot accept: {}",
            cause.message
        ),
        format!(
            "Values written through a query or ResMut are checked like any other input. {}",
            cause.hint
        ),
    )
}

fn command_failed(system: &str, index: usize, what: &str, cause: &str, hint: &str) -> Diagnostic {
    Diagnostic::error(
        "script_command_failed",
        format!("Command {index} of system '{system}' ({what}) failed: {cause}"),
        format!(
            "The commands before it were applied, as for a native system that fails midway. {hint}"
        ),
    )
}

/// Applies a system's commands in order.
fn apply_commands(world: &mut World, system: &str, bytes: &[u8]) -> Result<()> {
    if bytes.is_empty() {
        return Ok(());
    }
    let commands = decode_commands(bytes).map_err(|cause| {
        command_failed(
            system,
            0,
            "decoding",
            &cause,
            "Rebuild the game code with this engine's SDK.",
        )
    })?;
    let mut spawned: Vec<Entity> = Vec::new();
    for (index, command) in commands.iter().enumerate() {
        let resolve = |target: Target, spawned: &[Entity]| -> Result<Entity> {
            match target {
                Target::Existing(entity) => Ok(entity),
                Target::New(n) => spawned.get(n as usize).copied().ok_or_else(|| {
                    command_failed(
                        system,
                        index,
                        "entity",
                        "it names an entity not spawned yet",
                        "Spawn before using the new entity.",
                    )
                }),
            }
        };
        let fail = |what: &str, cause: Diagnostic| {
            command_failed(system, index, what, &cause.message, &cause.hint)
        };
        match command {
            Command::Spawn { .. } => spawned.push(world.spawn().map_err(|c| fail("spawn", c))?),
            Command::Despawn(target) => {
                let entity = resolve(*target, &spawned)?;
                world.despawn(entity).map_err(|c| fail("despawn", c))?;
            }
            Command::Insert {
                target,
                component: name,
                bytes,
            } => {
                let entity = resolve(*target, &spawned)?;
                let what = format!("insert {name}");
                let (id, size) = component(world, name, system).map_err(|c| fail(&what, c))?;
                if bytes.len() != size {
                    return Err(command_failed(
                        system,
                        index,
                        &what,
                        "the value has the wrong size",
                        "Rebuild the game code with this engine's SDK.",
                    ));
                }
                world
                    .insert_bytes(entity, id, bytes)
                    .map_err(|c| fail(&what, c))?;
            }
            Command::Remove {
                target,
                component: name,
            } => {
                let entity = resolve(*target, &spawned)?;
                let what = format!("remove {name}");
                let (id, _) = component(world, name, system).map_err(|c| fail(&what, c))?;
                world.remove_by_id(entity, id).map_err(|c| fail(&what, c))?;
            }
            Command::Send { event, bytes } => {
                let what = format!("send {event}");
                let id = event_id(world, event, system).map_err(|c| fail(&what, c))?;
                world.send_bytes(id, bytes).map_err(|c| fail(&what, c))?;
            }
            Command::SetParent { child, parent } => {
                let child = resolve(*child, &spawned)?;
                let parent = resolve(*parent, &spawned)?;
                world
                    .set_parent(child, parent)
                    .map_err(|c| fail("set_parent", c))?;
            }
            Command::RemoveParent(child) => {
                let child = resolve(*child, &spawned)?;
                world
                    .remove_parent(child)
                    .map_err(|c| fail("remove_parent", c))?;
            }
        }
    }
    Ok(())
}
